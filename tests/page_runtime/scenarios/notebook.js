/* 运行时场景：小本本：列表与来源、新建时的文件名校验、原文模式与改名、遗忘 / 删除 / 彻底删除、回收站与已遗忘、索引。
 * 由 tests/test_page_runtime.py 起后端后运行；单独运行需要环境变量 MP_PORT。 */
"use strict";
const { boot, assert, until, sleep, section, summary } = require("../harness.js");

(async () => {
  await (await boot()).reset();
  const p = await boot();
  const { $, $$, text, find, click, input, change } = p;
  await until(() => $(".nav-item"), "导航出现");

  section("B1 小本本列表");
  click(find(".nav-item", "小本本"));
  await until(() => $(".row"), "文件行出现");
  await sleep(60);
  const rows = $$(".row");
  console.log("  行:", rows.map((r) => text($(".row-name", r))));
  assert($("select[data-fk=notebook-picker]"), "两台机器人时出现机器人选择框");
  assert(!find(".row", "journal-20261101"), "日记默认折叠，不在主列表");
  const toggle = $(".group-toggle");
  assert(toggle && /日记/.test(text(toggle)), "有『日记 · N 篇』折叠组: " + text(toggle));
  click(toggle);
  await sleep(30);
  assert(find(".row", "journal-20261101"), "展开后能看到日记");
  assert($$(".chips button").map((b) => text(b)).join("|").includes("人物"), "类型筛选芯片: " + $$(".chips button").map((b) => text(b)).join("|"));
  const plans = find(".row", "plans.md");
  assert(plans && /悬空链接/.test(text(plans)), "plans.md 标出悬空链接: " + text(plans));
  const big = find(".row", "big.md");
  assert(big && /偏长/.test(text(big)), "big.md 标出偏长: " + (big && text(big)));
  assert(/小明/.test(text(plans)), "plans.md 行里有来源(小明)：" + text(plans));
  const foot = $(".list-foot");
  console.log("  底部入口:", text(foot));
  assert(/已遗忘/.test(text(foot)) && /回收站/.test(text(foot)) && /索引/.test(text(foot)) && /整理/.test(text(foot)), "列表底部有 索引/已遗忘/回收站/整理 入口");

  section("B2 文件详情：来源、链接");
  click(plans);
  await until(() => /plans\.md/.test(text($("[data-detail-heading]"))) && $(".pane-detail .md"), "plans.md 详情");
  const detail = $(".pane-detail");
  assert(/小明/.test(text(detail)) && /群聊「合成测试群」/.test(text(detail)), "详情里来源含说话人和群名（审计）: " + text($(".meta-grid", detail)));
  assert($$(".md-wiki.is-missing", detail).length === 1, "悬空的 [[missing-file]] 标成不可点");
  assert($$("input[type=checkbox], .md-task", detail).length >= 0, "任务列表渲染");
  console.log("  任务项:", $$(".md-task-item", detail).length);
  click($$("button.md-wiki", detail)[0]);
  await until(() => /user-10001\.md/.test(text($("[data-detail-heading]"))), "点 [[user-10001]] 打开人物档案");

  section("B3 新建：人物档案命名校验");
  click(find("button", "新建"));
  await until(() => $(".editor input"), "新建编辑器");
  const fileInput = $$(".editor input").find((e) => e.getAttribute("placeholder") === "user-123456.md");
  const typeSel = $(".editor select");
  const desc = $$(".editor input").filter((e) => e !== fileInput)[0];
  input(fileInput, "user-2002.md");
  input(desc, "新同学");
  change(typeSel, "note");
  await sleep(20);
  click(find(".detail-head button", "创建"));
  await sleep(60);
  const errs = $$(".editor .field-error").filter((e) => !e.hidden).map((e) => e.textContent);
  console.log("  错误提示:", errs);
  assert(errs.some((e) => /人物/.test(e)), "user-ID.md 配 note 类型被拦：" + errs);
  change(typeSel, "person");
  await sleep(20);
  input($(".editor textarea"), "称呼：新同学");
  await sleep(20);
  click(find(".detail-head button", "创建"));
  await until(() => $(".overlay .diff"), "创建前显示对比");
  click(find(".overlay button", "创建"));
  await until(() => p.lastCall("file/save"), "file/save");
  const cs = p.lastCall("file/save");
  assert(cs.body.file === "user-2002.md" && cs.body.type === "person" && cs.body.oldFile === "" && cs.body.mode === "fields", "新建 payload: " + JSON.stringify(cs.body));
  await until(() => /user-2002\.md/.test(text($("[data-detail-heading]"))) , "保存后打开新文件");
  const disk = await p.peek("notebook", "Bot-A", "user-2002.md");
  assert(disk.content && /type: person/.test(disk.content), "磁盘上有新文件");

  section("B4 原文模式 + 改名");
  click(find(".detail-actions button", "编辑"));
  await until(() => $(".editor select"), "编辑器");
  click(find(".segmented button", "原文"));
  await sleep(20);
  const raw = $(".editor textarea");
  assert(raw && /---/.test(raw.value), "原文模式显示含 frontmatter 的完整文件");
  input(raw, raw.value + "\n追加一行原文。");
  click(find(".detail-head button", "保存"));
  await until(() => $(".overlay .diff"), "原文保存前对比");
  click(find(".overlay button", "保存"));
  await until(() => p.lastCall("file/save").body.mode === "raw", "raw 模式 payload");
  const rs = p.lastCall("file/save");
  assert(rs.body.mode === "raw" && rs.body.content.includes("追加一行原文") && rs.body.oldFile === "user-2002.md", "raw payload: " + JSON.stringify(rs.body).slice(0, 200));
  await sleep(120);

  section("B5 遗忘 / 删除 / 彻底删除");
  click(find(".row", "keep-calm.md"));
  await until(() => /keep-calm\.md/.test(text($("[data-detail-heading]"))), "打开约定类");
  assert(/约定/.test(text($(".pane-detail .tag"))), "类型标签『约定』");
  click(find(".detail-actions button", "遗忘"));
  await until(() => $(".overlay"), "遗忘确认");
  console.log("  遗忘确认:", text($(".overlay")).slice(0, 200));
  assert(/已遗忘/.test(text($(".overlay"))), "遗忘确认说明去向");
  click(find(".overlay button", "遗忘"));
  await until(() => p.lastCall("file/forget"), "file/forget");
  await sleep(150);
  assert(!find(".row", "keep-calm.md"), "遗忘后从列表消失");
  click(find(".row", "plans.md"));
  await until(() => /plans\.md/.test(text($("[data-detail-heading]"))), "打开 plans");
  click(find(".detail-actions button", "删除"));
  await until(() => $(".overlay"), "删除确认");
  assert(/回收站/.test(text($(".overlay"))), "删除确认写明回收站");
  click(find(".overlay button", "取消"));
  await until(() => !$(".overlay"), "取消删除");
  const purgeBtn = find(".danger-zone button", "彻底删除");
  assert(purgeBtn, "有『彻底删除（含历史）』按钮");
  click(purgeBtn);
  await until(() => $(".overlay"), "彻底删除确认");
  const pt = text($(".overlay"));
  assert(/无法撤销/.test(pt) && /历史版本/.test(pt) && /回收站/.test(pt) && /整理记录/.test(pt), "彻底删除确认写清后果: " + pt.slice(0, 200));
  assert(document_active_is_cancel(p), "危险确认默认焦点在『取消』上");
  click(find(".overlay button", "取消"));
  await until(() => !$(".overlay"), "取消彻底删除");

  section("B6 已遗忘 / 回收站");
  click(find(".foot-link", "已遗忘"));
  await until(() => /回收站与已遗忘/.test(text($(".pane-detail"))), "维护面板");
  await sleep(100);
  console.log("  面板:", text($(".pane-detail")).slice(0, 260));
  click(find("[role=tab]", "已遗忘"));
  await sleep(60);
  assert(find(".item-row", "stale.md"), "已遗忘里有 stale.md");
  assert(find(".item-row", "keep-calm.md"), "刚遗忘的 keep-calm.md 也在");
  click(find(".item-row button", "查看") || find("button", "查看"));
  await until(() => $(".overlay .viewer"), "查看已遗忘内容");
  click(find(".overlay button", "关闭"));
  await until(() => !$(".overlay"), "关闭查看");
  const keep = find(".item-row", "keep-calm.md");
  click(find("button", "恢复", keep));
  await until(() => p.lastCall("forgotten/restore"), "forgotten/restore");
  await sleep(120);
  click(find("[role=tab]", "回收站"));
  await sleep(80);
  const trashed = find(".item-row", "trashed.md");
  assert(trashed, "回收站里有 trashed.md");
  assert(trashed && find("button", "彻底删除（含历史）", trashed), "回收站里不在册的文件有『彻底删除（含历史）』");
  click(find("button", "查看", trashed));
  await until(() => $(".overlay .viewer"), "查看回收站条目");
  click(find(".overlay button", "关闭"));
  await until(() => !$(".overlay"), "关闭");
  click(find("button", "删除这份副本", trashed));
  await until(() => $(".overlay"), "删除回收站副本确认");
  click(find(".overlay button", "取消"));
  await until(() => !$(".overlay"), "取消");
  click(find("button", "恢复", trashed));
  await until(() => p.lastCall("trash/restore"), "trash/restore");

  section("B7 索引");
  click(find(".foot-link", "索引"));
  await until(() => $(".meters"), "索引面板");
  const idx = $(".pane-detail textarea");
  assert(idx && idx.value.length > 0, "索引内容");
  console.log("  索引健康:", $$(".notice").map((n) => text(n)));
  input(idx, idx.value + "\n## 手加的分组\n");
  click(find(".detail-head button", "保存"));
  await until(() => $(".overlay .diff"), "索引保存前对比");
  click(find(".overlay button", "保存"));
  await until(() => p.lastCall("index/save"), "index/save");
  await sleep(100);
  click(find(".detail-head button", "按文件重建"));
  await until(() => $(".overlay"), "重建确认");
  assert(/回收站/.test(text($(".overlay"))), "重建确认写明旧索引会进回收站");
  click(find(".overlay button", "按文件重建"));
  await until(() => p.lastCall("index/rebuild"), "index/rebuild");

  console.log("\nuncaught:", p.uncaught().map((e) => String(e && e.stack || e).slice(0, 300)));
  assert(p.uncaught().length === 0, "没有未捕获错误");
  process.exit(summary() ? 0 : 1);
})().catch((err) => {
  console.error("FATAL", err);
  process.exit(2);
});

function document_active_is_cancel(p) {
  const a = p.document.activeElement;
  return a && /取消/.test(a.textContent);
}
